function addKeys(string $file, array $newKeys, string $langLabel): array
{
    $content = file_get_contents($file);
    if ($content === false) {
        return [0, 0, "Could not read $file"];
    }
    $existing = require $file;
    $added = 0;
    $skipped = 0;
    foreach ($newKeys as $k => $v) {
        if (!array_key_exists($k, $existing)) {
            $existing[$k] = $v;
            $added++;
        } else {
            $skipped++;
        }
    }
    $php = "<?php\n/**\n * $langLabel Language File\n * APS Dream Home - Real Estate CRM\n */\nreturn " . var_export($existing, true) . ";\n";
    file_put_contents($file, $php);
    return [$added, $skipped, count($existing)];
}

